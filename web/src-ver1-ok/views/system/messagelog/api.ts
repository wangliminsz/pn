import { request } from '/@/utils/service';
import { PageQuery, InfoReq, DelReq } from '@fast-crud/fast-crud';

export const apiPrefix = '/api/notify/messagelog/';

export function GetList(query: PageQuery) {
	return request({
		url: apiPrefix,
		method: 'get',
		params: query,
	});
}

export function GetObj(id: InfoReq) {
	return request({
		url: apiPrefix + id,
		method: 'get',
	});
}

export function DelObj(id: DelReq) {
	return request({
		url: apiPrefix + id + '/',
		method: 'delete',
		data: { id },
	});
}
